"""Export a CALM document as an idempotent Gremlin-Groovy script for Amazon Neptune.

Design choices (all deliberate, all Neptune-friendly):

* **One self-contained traversal per line, no variables.** Each line can be pasted into the
  Gremlin console, loaded with ``:load``, or submitted one by one to a Neptune endpoint.
* **Upserts, not inserts.** ``g.V(id).fold().coalesce(unfold(), addV(...))`` is Neptune's
  documented get-or-create idiom, so re-running the script never duplicates anything.
* **Application-supplied ids.** Vertex ids are ``<architecture>/<unique-id>``; Neptune accepts
  user-supplied string ids, which turns every lookup into an index hit.
* **Edges are get-or-created per (source, label, target)** with the
  ``inE(label).where(outV().as('s'))`` pattern; properties are re-applied on every run.
* **Replace mode** (default) first drops the architecture's previous vertices so the graph
  is a snapshot of the document. ``--no-replace`` keeps stale data.

Neptune stores multi-valued properties on vertices only (``set`` cardinality); on edges lists
are flattened to a single `` | ``-separated string.
"""

from __future__ import annotations

import argparse
import json
import sys
import urllib.request
from pathlib import Path
from typing import Any

from graph.model import Edge, GraphModel, Vertex, from_calm, safe_identifier


def gstr(value: str) -> str:
    """Groovy single-quoted string literal (no interpolation, only ``\\`` and ``'`` escape)."""
    escaped = (
        value.replace("\\", "\\\\").replace("'", "\\'").replace("\n", "\\n").replace("\r", "\\r")
    )
    return f"'{escaped}'"


def gval(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    return gstr(str(value))


def vertex_statement(v: Vertex) -> str:
    label = safe_identifier(v.label)
    parts = [
        f"g.V({gstr(v.uid)}).fold()"
        f".coalesce(__.unfold(), __.addV({gstr(label)}).property(T.id, {gstr(v.uid)}))"
    ]
    for key, value in sorted(v.props.items()):
        if isinstance(value, list):
            parts.extend(f".property(set, {gstr(key)}, {gval(item)})" for item in value)
        else:
            parts.append(f".property(single, {gstr(key)}, {gval(value)})")
    parts.append(".iterate()")
    return "".join(parts)


def edge_statement(e: Edge) -> str:
    label = safe_identifier(e.type)
    parts = [
        f"g.V({gstr(e.source)}).as('s').V({gstr(e.target)}).as('t')"
        f".coalesce(__.inE({gstr(label)}).where(__.outV().as('s')), "
        f"__.addE({gstr(label)}).from('s').to('t').property(T.id, {gstr(e.uid)}))"
    ]
    for key, value in sorted(e.props.items()):
        flat = " | ".join(map(str, value)) if isinstance(value, list) else value
        parts.append(f".property({gstr(key)}, {gval(flat)})")
    parts.append(".iterate()")
    return "".join(parts)


def build_statements(model: GraphModel, *, replace: bool = True) -> list[str]:
    statements: list[str] = []
    if replace:
        statements.append(f"g.V().has('architecture', {gstr(model.architecture)}).drop().iterate()")
    nodes = [v for v in model.vertices if v.label != "Control"]
    controls = [v for v in model.vertices if v.label == "Control"]
    statements += [vertex_statement(v) for v in nodes + controls]
    statements += [edge_statement(e) for e in model.edges]
    return statements


HEADER = """\
// Generated by calm-arch-discovery from CALM architecture '{architecture}'.
// {vertices} vertices, {edges} edges. One idempotent traversal per line.
//
// Run it:
//   Gremlin console : :remote connect tinkerpop.server conf/neptune-remote.yaml
//                     :remote console
//                     :load {name}
//   any client      : submit each non-comment line as its own Gremlin query
//   local check     : docker compose --profile gremlin up -d gremlin
//                     python -m graph.gremlin_exporter <doc> --submit http://localhost:8182
"""


def render(model: GraphModel, name: str, *, replace: bool = True) -> str:
    header = HEADER.format(
        architecture=model.architecture,
        vertices=len(model.vertices),
        edges=len(model.edges),
        name=name,
    )
    return header + "\n" + "\n".join(build_statements(model, replace=replace)) + "\n"


def _local_url(url: str) -> str:
    """Only local Gremlin Servers are allowed; use 127.0.0.1 (Windows resolves ``localhost``
    to IPv6 first and every request then waits ~2s for the fallback)."""
    if not url.startswith(("http://localhost", "http://127.0.0.1")):
        raise ValueError("--submit is for a local Gremlin Server only; Neptune needs SigV4 auth")
    return url.replace("//localhost", "//127.0.0.1", 1)


def query(url: str, gremlin: str) -> list[Any]:
    """Run one Gremlin string on a local Gremlin Server and return the plain-JSON result."""
    req = urllib.request.Request(  # noqa: S310 - scheme restricted by _local_url
        _local_url(url),
        data=json.dumps({"gremlin": gremlin}).encode(),
        headers={"Content-Type": "application/json", "Accept": "application/json"},
    )
    with urllib.request.urlopen(req, timeout=30) as resp:  # noqa: S310
        data = json.loads(resp.read())["result"]["data"]
    result = untype(data)
    return result if isinstance(result, list) else [result]


def untype(value: Any) -> Any:
    """Collapse GraphSON 3 ``{"@type": ..., "@value": ...}`` wrappers into plain Python."""
    if isinstance(value, list):
        return [untype(v) for v in value]
    if not (isinstance(value, dict) and "@type" in value):
        return value
    kind, inner = value["@type"], value["@value"]
    if kind == "g:Map":
        pairs = iter(inner)
        out: dict[Any, Any] = {}
        for k, v in zip(pairs, pairs, strict=True):
            key = untype(k)
            out[key if isinstance(key, (str, int, float, bool)) else json.dumps(key)] = untype(v)
        return out
    if kind == "g:Path":
        return untype(inner["objects"])
    if kind in ("g:Vertex", "g:Edge"):
        return untype(inner["id"])
    return untype(inner)


def submit(url: str, statements: list[str]) -> int:
    """Execute each statement on a local Gremlin Server (verification, not deployment)."""
    for stmt in statements:
        query(url, stmt)
    return len(statements)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="calm-export-gremlin", description=__doc__.split("\n")[0])
    parser.add_argument("document", type=Path, help="CALM JSON document")
    parser.add_argument("-o", "--output", type=Path, help="write the .groovy script here")
    parser.add_argument(
        "--no-replace",
        action="store_true",
        help="do not drop the architecture's existing vertices first",
    )
    parser.add_argument(
        "--submit",
        metavar="URL",
        help="also execute the script on a local Gremlin Server, e.g. http://localhost:8182",
    )
    args = parser.parse_args(argv)

    model = from_calm(json.loads(args.document.read_text(encoding="utf-8")))
    name = args.output.name if args.output else "calm-load.groovy"
    script = render(model, name, replace=not args.no_replace)
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(script, encoding="utf-8", newline="\n")
        print(
            f"wrote {args.output} ({len(model.vertices)} vertices, {len(model.edges)} edges)",
            file=sys.stderr,
        )
    else:
        sys.stdout.write(script)
    if args.submit:
        count = submit(args.submit, build_statements(model, replace=not args.no_replace))
        print(f"executed {count} statements on {args.submit}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
